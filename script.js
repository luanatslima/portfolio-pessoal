// TIPOS DE DADOS E VARIÁVEIS:

let nome = 'Luana';
console.log(`Olá, ${nome}! Seja bem-vinda(o)!`); // STRING  

let idade = 18;
console.log(`Você tem ${idade} anos.`); // NUMBER 

let maiorDeIdade = idade >= 18;
console.log(`Maior de idade: ${maiorDeIdade}`); // BOOLEAN 

let menorDeIdade = idade < 18;
console.log(`Menor de idade: ${menorDeIdade}`); // BOOLEAN

// Null: Variável Vazia
let endereco = null;
console.log(`Endereço: ${endereco}`);

// Undefined: Variável indefinida
let telefone = undefined;
console.log(`Telefone: ${telefone}`);

